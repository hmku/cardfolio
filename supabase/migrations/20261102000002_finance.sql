-- Adds the default categories to a household that has none yet. The migration runs it for
-- existing households; the sync runs it for any household that still has none.
create or replace function public.cardfolio_seed_categories(p_household uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  added integer;
begin
  if exists (select 1 from public.categories where household_id = p_household) then
    return 0;
  end if;
  insert into public.categories (household_id, name, kind, emoji, sort, plaid_categories)
  select p_household, seed.name, seed.kind, seed.emoji, seed.sort, seed.codes
  from (values
    ('Paychecks', 'income', '💼', 10, array['INCOME_SALARY', 'INCOME_WAGES', 'INCOME_CONTRACTOR', 'INCOME_GIG_ECONOMY', 'INCOME_MILITARY']),
    ('Interest & dividends', 'income', '📈', 20, array['INCOME_INTEREST_EARNED', 'INCOME_DIVIDENDS']),
    ('Other income', 'income', '💰', 30, array['INCOME']),
    ('Groceries', 'expense', '🛒', 100, array['FOOD_AND_DRINK_GROCERIES']),
    ('Restaurants & bars', 'expense', '🍽️', 110, array['FOOD_AND_DRINK']),
    ('Shopping', 'expense', '🛍️', 120, array['GENERAL_MERCHANDISE']),
    ('Travel', 'expense', '✈️', 130, array['TRAVEL']),
    ('Transportation', 'expense', '🚗', 140, array['TRANSPORTATION']),
    ('Rent & mortgage', 'expense', '🏠', 150, array['RENT_AND_UTILITIES_RENT', 'LOAN_PAYMENTS_MORTGAGE_PAYMENT']),
    ('Utilities & phone', 'expense', '💡', 160, array['RENT_AND_UTILITIES']),
    ('Home', 'expense', '🛠️', 170, array['HOME_IMPROVEMENT']),
    ('Entertainment', 'expense', '🎬', 180, array['ENTERTAINMENT']),
    ('Health', 'expense', '🩺', 190, array['MEDICAL']),
