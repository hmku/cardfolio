-- Plaid bank connections. Each item is one bank login connected through Plaid Link; its
-- accounts are the cards Plaid found there, each optionally linked to a Cardfolio account.
-- Only the server (service role) reads or writes these tables: the access token is
-- encrypted with PLAID_TOKEN_KEY before it is stored, and the browser goes through
-- /api/plaid/*.

create table public.plaid_items (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  plaid_item_id text not null unique,
  access_token_encrypted text not null,
  institution_id text,
  institution_name text,
  added_by uuid references auth.users(id) on delete set null,
  added_by_email text,
  -- 'ok', or 'reconnect' when the bank login needs to be entered again (Link update mode).
  status text not null default 'ok' check (status in ('ok', 'reconnect')),
  error_code text,
  consent_expires_at timestamptz,
  -- Phase 2: /transactions/sync cursor.
  transactions_cursor text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (household_id, id)
);

create table public.plaid_accounts (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  item_id bigint not null,
  plaid_account_id text not null unique,
  name text not null,
  official_name text,
  mask text,
  type text,
  subtype text,
  account_id bigint,
  -- 'auto' when matched by last digits, 'manual' when a person picked it (or cleared it).
  link_source text check (link_source in ('auto', 'manual')),
  created_at timestamptz not null default now(),
  constraint plaid_accounts_item_fkey foreign key (household_id, item_id)
    references public.plaid_items(household_id, id) on delete cascade,
  constraint plaid_accounts_account_fkey foreign key (household_id, account_id)
    references public.accounts(household_id, id) on delete set null (account_id)
);

create index idx_plaid_items_household on public.plaid_items(household_id);
create index idx_plaid_accounts_item on public.plaid_accounts(item_id);
create index idx_plaid_accounts_account on public.plaid_accounts(account_id);

alter table public.plaid_items enable row level security;
alter table public.plaid_accounts enable row level security;

-- No policies: signed-in browsers can't read these tables at all.
revoke all on public.plaid_items, public.plaid_accounts from anon, authenticated;
grant select, insert, update, delete on public.plaid_items, public.plaid_accounts to service_role;
