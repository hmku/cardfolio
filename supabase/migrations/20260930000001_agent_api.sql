-- Agent access and all-or-nothing writes.
--
-- * agent_keys: access keys for agents (MCP clients) acting for a household. Only a
--   SHA-256 hash is stored; the key itself is shown once in Settings.
-- * change_log: what agents changed, with the email or message it came from.
-- * cardfolio_* functions: multi-step writes (new card, product change, undo, credit
--   use) that used to be several browser requests now run as one transaction. They are
--   security invoker, so row-level security still applies to browser callers.

create table public.agent_keys (
  id uuid primary key default gen_random_uuid(),
  household_id uuid not null references public.households(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  key_hash text not null unique,
  key_prefix text not null,
  created_by text,
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  revoked_at timestamptz
);

create index idx_agent_keys_household on public.agent_keys(household_id);

create table public.change_log (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  actor text not null,
  action text not null,
  account_id bigint,
  summary text not null,
  source text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index idx_change_log_household on public.change_log(household_id, created_at desc);
create index idx_change_log_source on public.change_log(household_id, action, source) where source is not null;

alter table public.agent_keys enable row level security;
alter table public.change_log enable row level security;

-- Members create (hash only), list and revoke their household's keys in Settings.
create policy "members manage agent keys" on public.agent_keys for all
  using (public.is_cardfolio_member(household_id)) with check (public.is_cardfolio_member(household_id));
create policy "members read change log" on public.change_log for select
  using (public.is_cardfolio_member(household_id));

grant select, insert, update, delete on public.agent_keys to authenticated, service_role;
grant select on public.change_log to authenticated;
grant select, insert on public.change_log to service_role;

