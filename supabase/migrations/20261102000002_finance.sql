-- Household lists: members manage them.
create policy "members manage categories" on public.categories for all
  using (public.is_cardfolio_member(household_id)) with check (public.is_cardfolio_member(household_id));
create policy "members manage category rules" on public.category_rules for all
  using (public.is_cardfolio_member(household_id)) with check (public.is_cardfolio_member(household_id));
create policy "members manage manual accounts" on public.manual_accounts for all
  using (public.is_cardfolio_member(household_id)) with check (public.is_cardfolio_member(household_id));
grant select, insert, update, delete on public.categories, public.category_rules, public.manual_accounts to authenticated;

-- Synced data: members read it; only the user columns of transactions are writable.
create policy "members read transactions" on public.transactions for select
  using (public.is_cardfolio_member(household_id));
create policy "members update transactions" on public.transactions for update
  using (public.is_cardfolio_member(household_id)) with check (public.is_cardfolio_member(household_id));
grant select on public.transactions to authenticated;
grant update (category_id, category_source, notes, excluded, reviewed) on public.transactions to authenticated;

create policy "members read securities" on public.securities for select using (public.is_cardfolio_member(household_id));
create policy "members read holdings" on public.holdings for select using (public.is_cardfolio_member(household_id));
create policy "members read investment transactions" on public.investment_transactions for select using (public.is_cardfolio_member(household_id));
grant select on public.securities, public.holdings, public.investment_transactions to authenticated;

-- Snapshots: members read all of them and write only manual accounts' ones.
create policy "members read balance snapshots" on public.balance_snapshots for select
  using (public.is_cardfolio_member(household_id));
create policy "members add manual snapshots" on public.balance_snapshots for insert
  with check (manual_account_id is not null and public.is_cardfolio_member(household_id));
create policy "members change manual snapshots" on public.balance_snapshots for update
  using (manual_account_id is not null and public.is_cardfolio_member(household_id))
  with check (manual_account_id is not null and public.is_cardfolio_member(household_id));
create policy "members delete manual snapshots" on public.balance_snapshots for delete
  using (manual_account_id is not null and public.is_cardfolio_member(household_id));
grant select, insert, update, delete on public.balance_snapshots to authenticated;

revoke all on public.categories, public.category_rules, public.transactions, public.securities,
  public.holdings, public.investment_transactions, public.manual_accounts, public.balance_snapshots
  from anon;
grant select, insert, update, delete on public.categories, public.category_rules, public.transactions,
  public.securities, public.holdings, public.investment_transactions, public.manual_accounts,
  public.balance_snapshots to service_role;

