create or replace function public.reset_cardfolio_sequences()
returns void
language plpgsql
security definer
set search_path = 'public'
as $$
declare
  item text;
begin
  foreach item in array array['people', 'products', 'accounts', 'account_products', 'credits', 'credit_uses'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, %L), greatest(coalesce((select max(id) from public.%I), 0) + 1, 1), false)',
      'public.' || item,
      'id',
      item
    );
  end loop;
end;
$$;

revoke all on function public.reset_cardfolio_sequences() from public, anon, authenticated;
grant execute on function public.reset_cardfolio_sequences() to service_role;
