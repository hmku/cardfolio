-- Finance backbone: balances, transactions, categories, investments and net worth.
--
-- Plaid data (balances, transactions, holdings, investment transactions) is written only by
-- the server (service role) during a sync; signed-in members can read it, and may change a
-- few user-owned columns (a transaction's category, notes, excluded and reviewed flags, a
-- Plaid account's owner). Categories, category rules and manual accounts are the household's
-- own lists, managed from the browser.
--
-- Money is stored in integer cents. Sign convention (differs from Plaid's):
--   transactions.amount_cents and investment_transactions.amount_cents:
--     positive = money into the account (paycheck, refund, sale proceeds),
--     negative = money out of the account (purchase, fee, buying a security).
--     Plaid's own amounts are the opposite (positive = money out); the sync flips them.
--   plaid_accounts balance columns are stored as Plaid reports them (a card's current
--     balance is the positive amount owed).
--   balance_snapshots.balance_cents is the account's contribution to net worth: assets
--     positive, debts (credit cards, loans, manual liabilities) negative.
--   manual_accounts.balance_cents is the positive value or amount owed; `liability` says which.

-- pg_trgm makes "contains" searches over transaction text fast. Supabase keeps extensions in
-- the `extensions` schema; an existing install elsewhere is left where it is.
create schema if not exists extensions;
create extension if not exists pg_trgm with schema extensions;

-- ---------- plaid_items: sync bookkeeping ----------

alter table public.plaid_items
  add column if not exists last_synced_at timestamptz,
  -- Plaid's transactions_update_status from the last /transactions/sync
  -- (NOT_READY, INITIAL_UPDATE_COMPLETE, HISTORICAL_UPDATE_COMPLETE, ...).
  add column if not exists transactions_status text,
  -- Products the last sync could read for this login, e.g. {transactions,liabilities}.
  add column if not exists synced_products text[],
  add column if not exists investments_synced_at timestamptz,
  -- The webhook URL Plaid has for this login (set at Link or by /item/webhook/update), so a
  -- sync can point older logins at PLAID_WEBHOOK_URL once it is configured.
  add column if not exists webhook_url text;

-- ---------- plaid_accounts: balances, card statement details, owner ----------

alter table public.plaid_accounts
  add column if not exists current_balance_cents bigint,
  add column if not exists available_balance_cents bigint,
  add column if not exists credit_limit_cents bigint,
  add column if not exists currency text,
  add column if not exists balances_updated_at timestamptz,
  -- Credit cards, from /liabilities/get.
  add column if not exists last_statement_balance_cents bigint,
  add column if not exists last_statement_date date,
  add column if not exists minimum_payment_cents bigint,
  add column if not exists next_payment_due_date date,
  add column if not exists last_payment_cents bigint,
  add column if not exists last_payment_date date,
  add column if not exists is_overdue boolean,
  add column if not exists liabilities_updated_at timestamptz,
  -- Whose account this is (optional), for per-person net worth. Set from the browser.
  add column if not exists person_id bigint;

alter table public.plaid_accounts
  add constraint plaid_accounts_household_id_key unique (household_id, id),
  add constraint plaid_accounts_person_fkey foreign key (household_id, person_id)
    references public.people(household_id, id) on delete set null (person_id);

-- Members may read Plaid accounts (no secrets there) and set the owner; plaid_items stays
-- server-only because it holds the encrypted access token.
create policy "members read plaid accounts" on public.plaid_accounts for select
  using (public.is_cardfolio_member(household_id));
create policy "members update plaid accounts" on public.plaid_accounts for update
  using (public.is_cardfolio_member(household_id)) with check (public.is_cardfolio_member(household_id));
grant select on public.plaid_accounts to authenticated;
grant update (person_id) on public.plaid_accounts to authenticated;

-- A token-free view of each bank login, for showing institution names and sync status.
create view public.plaid_item_status with (security_barrier = true) as
  select id, household_id, institution_name, status, error_code, consent_expires_at,
         last_synced_at, transactions_status, synced_products, created_at
  from public.plaid_items
  where public.is_cardfolio_member(household_id);
revoke all on public.plaid_item_status from anon, authenticated;
grant select on public.plaid_item_status to authenticated, service_role;

-- ---------- categories ----------

create table public.categories (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  -- income and expense count in cash flow; transfer (card payments, moving money between
  -- your own accounts) never does.
  kind text not null default 'expense' check (kind in ('income', 'expense', 'transfer')),
  emoji text,
  color text,
  sort integer not null default 0,
  -- Plaid personal_finance_category codes that map to this category by default: primary
  -- (FOOD_AND_DRINK) or detailed (FOOD_AND_DRINK_GROCERIES). A detailed match wins over a
  -- primary one.
  plaid_categories text[] not null default '{}',
  created_at timestamptz not null default now(),
  unique (household_id, name),
  unique (household_id, id)
);

-- Household rules: a transaction whose merchant name or description contains match_text
-- (case-insensitive), optionally only on one account, gets category_id. Account-specific
-- rules beat general ones, then the longest match_text wins, then the oldest rule.
create table public.category_rules (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  match_text text not null check (length(trim(match_text)) > 0),
  match_field text not null default 'any' check (match_field in ('any', 'merchant', 'name')),
  plaid_account_id bigint,
  category_id bigint not null,
  -- When set, also marks matching transactions excluded (true) or included (false).
  set_excluded boolean,
  created_at timestamptz not null default now(),
  unique (household_id, id),
  constraint category_rules_category_fkey foreign key (household_id, category_id)
    references public.categories(household_id, id) on delete cascade,
  constraint category_rules_account_fkey foreign key (household_id, plaid_account_id)
    references public.plaid_accounts(household_id, id) on delete cascade
);

-- ---------- transactions ----------

create table public.transactions (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  plaid_account_id bigint not null,
  plaid_transaction_id text not null unique,
  -- For a posted transaction, the pending one it replaced (Plaid removes that one).
  pending_transaction_id text,
  date date not null,
  authorized_date date,
  -- Positive = money in, negative = money out (Plaid's sign flipped).
  amount_cents bigint not null,
  currency text,
  name text not null,
  merchant_name text,
  logo_url text,
  website text,
  plaid_category_primary text,
  plaid_category_detailed text,
  plaid_category_confidence text,
  pending boolean not null default false,
  payment_channel text,
  -- User fields (the browser may update these).
  category_id bigint,
  -- How category_id was chosen: 'rule', 'plaid' (default mapping) or 'manual' (a person).
  -- Syncs re-categorize 'rule'/'plaid' rows when Plaid modifies them, never 'manual' ones.
  category_source text check (category_source in ('rule', 'plaid', 'manual')),
  notes text,
  excluded boolean not null default false,
  reviewed boolean not null default false,
  search_text text generated always as (
    lower(coalesce(merchant_name, '') || ' ' || name || ' ' || coalesce(notes, ''))
  ) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (household_id, id),
  constraint transactions_account_fkey foreign key (household_id, plaid_account_id)
    references public.plaid_accounts(household_id, id) on delete cascade,
  constraint transactions_category_fkey foreign key (household_id, category_id)
    references public.categories(household_id, id) on delete set null (category_id)
);

create index idx_transactions_household_date on public.transactions(household_id, date desc, id desc);
create index idx_transactions_account_date on public.transactions(plaid_account_id, date desc);
create index idx_transactions_category on public.transactions(category_id);
create index idx_transactions_pending_id on public.transactions(pending_transaction_id) where pending_transaction_id is not null;

-- Trigram index for `search_text ilike '%coffee%'`, wherever pg_trgm is installed.
do $$
declare
  trgm_schema text;
begin
  select n.nspname into trgm_schema from pg_extension e join pg_namespace n on n.oid = e.extnamespace where e.extname = 'pg_trgm';
  execute format('create index idx_transactions_search on public.transactions using gin (search_text %I.gin_trgm_ops)', trgm_schema);
end;
$$;

create trigger transactions_touch_updated_at before update on public.transactions
  for each row execute function public.touch_updated_at();

-- ---------- investments ----------

create table public.securities (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  plaid_security_id text not null,
  name text,
  ticker_symbol text,
  type text,
  is_cash_equivalent boolean,
  close_price numeric,
  close_price_as_of date,
  currency text,
  updated_at timestamptz not null default now(),
  unique (household_id, plaid_security_id),
  unique (household_id, id)
);

-- Current positions, replaced on every holdings sync.
create table public.holdings (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  plaid_account_id bigint not null,
  security_id bigint not null,
  quantity numeric not null,
  cost_basis_cents bigint,
  institution_price numeric,
  institution_price_as_of date,
  institution_value_cents bigint,
  currency text,
  updated_at timestamptz not null default now(),
  unique (plaid_account_id, security_id),
  constraint holdings_account_fkey foreign key (household_id, plaid_account_id)
    references public.plaid_accounts(household_id, id) on delete cascade,
  constraint holdings_security_fkey foreign key (household_id, security_id)
    references public.securities(household_id, id) on delete cascade
);

create index idx_holdings_household on public.holdings(household_id);

create table public.investment_transactions (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  plaid_account_id bigint not null,
  plaid_investment_transaction_id text not null unique,
  security_id bigint,
  date date not null,
  name text not null,
  quantity numeric,
  -- Positive = cash into the account (a sale, a dividend), negative = cash out (a buy, a fee).
  amount_cents bigint not null,
  price numeric,
  fees_cents bigint,
  type text,
  subtype text,
  currency text,
  created_at timestamptz not null default now(),
  constraint investment_transactions_account_fkey foreign key (household_id, plaid_account_id)
    references public.plaid_accounts(household_id, id) on delete cascade,
  constraint investment_transactions_security_fkey foreign key (household_id, security_id)
    references public.securities(household_id, id) on delete set null (security_id)
);

create index idx_investment_transactions_household_date on public.investment_transactions(household_id, date desc, id desc);
create index idx_investment_transactions_account on public.investment_transactions(plaid_account_id, date desc);

-- ---------- manual accounts and net worth history ----------

create table public.manual_accounts (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  kind text not null default 'other' check (kind in (
    'cash', 'investment', 'private_investment', 'retirement', 'real_estate', 'vehicle',
    'crypto', 'loan', 'other'
  )),
  -- A debt (counts negative in net worth) rather than an asset.
  liability boolean not null default false,
  balance_cents bigint not null default 0,
  currency text not null default 'USD',
  balance_updated_at timestamptz not null default now(),
  person_id bigint,
  notes text,
  archived boolean not null default false,
  sort integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (household_id, id),
  constraint manual_accounts_person_fkey foreign key (household_id, person_id)
    references public.people(household_id, id) on delete set null (person_id)
);

create trigger manual_accounts_touch_updated_at before update on public.manual_accounts
  for each row execute function public.touch_updated_at();

-- One balance per account per day: Plaid accounts from each sync, manual accounts carried
-- forward daily by the sync job (and written by the browser when a balance is edited).
create table public.balance_snapshots (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  date date not null,
  plaid_account_id bigint,
  manual_account_id bigint,
  -- Contribution to net worth: assets positive, debts negative.
  balance_cents bigint not null,
  currency text,
  created_at timestamptz not null default now(),
  check ((plaid_account_id is null) <> (manual_account_id is null)),
  constraint balance_snapshots_account_day_key unique nulls not distinct (plaid_account_id, manual_account_id, date),
  constraint balance_snapshots_plaid_fkey foreign key (household_id, plaid_account_id)
    references public.plaid_accounts(household_id, id) on delete cascade,
  constraint balance_snapshots_manual_fkey foreign key (household_id, manual_account_id)
    references public.manual_accounts(household_id, id) on delete cascade
);

create index idx_balance_snapshots_household_date on public.balance_snapshots(household_id, date);

