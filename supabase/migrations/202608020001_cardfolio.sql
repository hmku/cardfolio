create or replace function public.reset_cardfolio_sequences()
returns void
language plpgsql
security definer
set search_path = 'public'
as $$
declare
  item text;
begin
  foreach item in array array['card_types', 'accounts', 'benefits', 'benefit_usage'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, %L), greatest(coalesce((select max(id) from public.%I), 0) + 1, 1), false)',
      'public.' || item,
      'id',
      item
    );
  end loop;
end;
$$;

revoke all on function public.reset_cardfolio_sequences() from public, anon, authenticated;
grant execute on function public.reset_cardfolio_sequences() to service_role;

revoke all on function public.is_cardfolio_member(uuid) from public;
revoke all on function public.is_cardfolio_owner(uuid) from public;
grant execute on function public.is_cardfolio_member(uuid) to authenticated, service_role;
grant execute on function public.is_cardfolio_owner(uuid) to authenticated, service_role;
