create extension if not exists pgcrypto;

create table if not exists public.households (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.household_members (
  household_id uuid not null references public.households(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  email text not null,
  role text not null default 'member' check (role in ('owner', 'member')),
  created_at timestamptz not null default now(),
  primary key (household_id, user_id),
  unique (user_id)
);

create table if not exists public.household_invitations (
  id uuid primary key default gen_random_uuid(),
  household_id uuid not null references public.households(id) on delete cascade,
  email text not null,
  role text not null default 'member' check (role in ('owner', 'member')),
  invited_by uuid references auth.users(id) on delete set null,
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  unique (household_id, email)
);

create table if not exists public.app_meta (
  household_id uuid not null references public.households(id) on delete cascade,
  key text not null,
  value text not null,
  primary key (household_id, key)
);

create table if not exists public.card_types (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  name text not null,
  issuer text not null default 'Other',
  kind text not null default 'personal',
  annual_fee integer not null default 0 check (annual_fee >= 0),
  created_at timestamptz not null default now(),
  unique (household_id, name),
  unique (household_id, id)
);

create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  owner text not null,
  card_type_id bigint not null,
  kind text not null,
  card_index text,
  applied_on date,
  approved_on date,
  opened_how text,
  offer text,
  annual_fee integer not null default 0 check (annual_fee >= 0),
  bonus_received boolean not null default false,
  status text not null default 'pending' check (status in ('active', 'closed', 'pending', 'declined')),
  closed_on date,
  closed_how text,
  source_row integer,
  created_at timestamptz not null default now(),
  unique (household_id, id),
  constraint accounts_card_type_id_fkey foreign key (household_id, card_type_id) references public.card_types(household_id, id) on delete restrict
);

create table if not exists public.benefits (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  card_type_id bigint not null,
  name text not null,
  amount integer not null default 0 check (amount >= 0),
  frequency text not null default 'calendar year',
  unique (household_id, id),
  constraint benefits_card_type_id_fkey foreign key (household_id, card_type_id) references public.card_types(household_id, id) on delete cascade
);

create table if not exists public.benefit_usage (
  id bigint generated by default as identity primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  account_id bigint not null,
  benefit_id bigint not null,
  period_key text not null,
  used boolean not null default false,
  used_on date,
  unique (account_id, benefit_id, period_key),
  constraint benefit_usage_account_id_fkey foreign key (household_id, account_id) references public.accounts(household_id, id) on delete cascade,
  constraint benefit_usage_benefit_id_fkey foreign key (household_id, benefit_id) references public.benefits(household_id, id) on delete cascade
);

create index if not exists idx_accounts_household_owner_status on public.accounts(household_id, owner, status);
create index if not exists idx_accounts_household_card_type_status on public.accounts(household_id, card_type_id, status);
create unique index if not exists idx_accounts_household_source_row on public.accounts(household_id, source_row) where source_row is not null;
create index if not exists idx_benefits_household_card_type on public.benefits(household_id, card_type_id);
create index if not exists idx_usage_household_period on public.benefit_usage(household_id, period_key, used);
create index if not exists idx_invitations_household_email on public.household_invitations(household_id, lower(email));

